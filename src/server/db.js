export async function createDoc(serverId, userId, name, content = '') {
  let finalName = name;
  let suffix = 2;
  while (await getDocByName(serverId, finalName)) {
    finalName = `${name} (${suffix++})`;
  }
  const now = Date.now();
  return one(
    `INSERT INTO docs (server_id, name, content, updated_at, updated_by, created_at, created_by)
     VALUES ($1, $2, $3, $4, $5, $6, $7) RETURNING *`,
    [serverId, finalName, content, now, userId, now, userId],
  );
}

