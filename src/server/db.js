import pg from 'pg';
import { randomBytes } from 'node:crypto';

const { Pool } = pg;

// Interpret BIGINT columns (ids, timestamps, counts) as JS numbers.
pg.types.setTypeParser(20, (value) => Number(value));

const DEFAULT_URL = 'postgres://postgres:postgres@localhost:5432/chatterbox';

function sslConfig() {
  const mode = process.env.PGSSL;
  if (!mode || mode === 'disable') return undefined;
  if (mode === 'no-verify') return { rejectUnauthorized: false };
  return { rejectUnauthorized: true };
}

export const pool = new Pool({
  connectionString: process.env.DATABASE_URL || DEFAULT_URL,
  max: Number(process.env.PG_POOL_MAX) || 10,
  idleTimeoutMillis: 30_000,
  connectionTimeoutMillis: 10_000,
  ssl: sslConfig(),
  application_name: 'chatterbox',
});

pool.on('error', (err) => {
  console.error('postgres idle client error', err.message);
});

const SCHEMA = `
  CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    salt TEXT NOT NULL,
    hash TEXT NOT NULL,
    color TEXT NOT NULL,
    created_at BIGINT NOT NULL
  );
  CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_lower ON users (lower(username));

  CREATE TABLE IF NOT EXISTS sessions (
    token TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS servers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    owner_id INTEGER NOT NULL REFERENCES users(id),
    invite_code TEXT NOT NULL UNIQUE,
    created_at BIGINT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS server_members (
    server_id INTEGER NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    joined_at BIGINT NOT NULL,
    PRIMARY KEY (server_id, user_id)
  );

  CREATE TABLE IF NOT EXISTS channels (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id INTEGER NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('text', 'voice')),
    position INTEGER NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id INTEGER NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id),
    content TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    edited_at BIGINT,
    thread_id INTEGER REFERENCES messages(id) ON DELETE CASCADE,
    merge_id INTEGER
  );

  CREATE TABLE IF NOT EXISTS attachments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id INTEGER REFERENCES messages(id) ON DELETE CASCADE,
    channel_id INTEGER NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
    uploaded_by INTEGER NOT NULL REFERENCES users(id),
    name TEXT NOT NULL,
    mime TEXT NOT NULL,
    size BIGINT NOT NULL,
    stored_name TEXT NOT NULL,
    created_at BIGINT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS docs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id INTEGER NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    content TEXT NOT NULL DEFAULT '',
    updated_at BIGINT NOT NULL,
    updated_by INTEGER REFERENCES users(id),
    created_at BIGINT NOT NULL,
    created_by INTEGER REFERENCES users(id),
    mode TEXT NOT NULL DEFAULT 'review' CHECK (mode IN ('live', 'review'))
  );

  CREATE TABLE IF NOT EXISTS merge_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id INTEGER NOT NULL REFERENCES docs(id) ON DELETE CASCADE,
    server_id INTEGER NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id),
    content TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at BIGINT NOT NULL,
    resolved_at BIGINT
  );

  CREATE TABLE IF NOT EXISTS merge_voters (
    request_id INTEGER NOT NULL REFERENCES merge_requests(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (request_id, user_id)
  );

  CREATE TABLE IF NOT EXISTS merge_votes (
    request_id INTEGER NOT NULL REFERENCES merge_requests(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    vote TEXT NOT NULL CHECK (vote IN ('approve', 'reject')),
    created_at BIGINT NOT NULL,
    PRIMARY KEY (request_id, user_id)
  );

  CREATE INDEX IF NOT EXISTS idx_messages_channel ON messages(channel_id, id);
  CREATE INDEX IF NOT EXISTS idx_messages_thread ON messages(thread_id);
  CREATE INDEX IF NOT EXISTS idx_members_user ON server_members(user_id);
  CREATE INDEX IF NOT EXISTS idx_attach_message ON attachments(message_id);
  CREATE INDEX IF NOT EXISTS idx_attach_channel ON attachments(channel_id);
  CREATE INDEX IF NOT EXISTS idx_docs_server ON docs(server_id);
  CREATE INDEX IF NOT EXISTS idx_merge_server ON merge_requests(server_id, status);
`;

export async function initDb() {
  await pool.query(SCHEMA);
}

export async function ping() {
  await pool.query('SELECT 1');
}

export async function closeDb() {
  await pool.end();
}

