async function insertChannel(q, serverId, name, type) {
  const row = await q(
    `INSERT INTO channels (server_id, name, type, position, created_at)
     VALUES ($1, $2, $3, (SELECT COALESCE(MAX(position), 0) + 1 FROM channels WHERE server_id = $1), $4)
     RETURNING *`,
    [serverId, name, type, Date.now()],
  );
  return row.rows[0];
}

export async function createServer(name, ownerId) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const { rows } = await client.query(
      'INSERT INTO servers (name, owner_id, invite_code, created_at) VALUES ($1, $2, $3, $4) RETURNING *',
      [name, ownerId, randomBytes(4).toString('hex'), Date.now()],
    );
    const server = rows[0];
    await client.query(
      'INSERT INTO server_members (server_id, user_id, joined_at) VALUES ($1, $2, $3) ON CONFLICT DO NOTHING',
      [server.id, ownerId, Date.now()],
    );
    await insertChannel(client.query.bind(client), server.id, 'general', 'text');
    await insertChannel(client.query.bind(client), server.id, 'General', 'voice');
    await client.query('COMMIT');
    return server;
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
  }
}

