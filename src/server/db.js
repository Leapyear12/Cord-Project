/* ----------------------------- merge requests ----------------------------- */

export async function createMergeRequest({ docId, serverId, userId, content, voters }) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const { rows } = await client.query(
      `INSERT INTO merge_requests (doc_id, server_id, user_id, content, created_at)
       VALUES ($1, $2, $3, $4, $5) RETURNING id`,
      [docId, serverId, userId, content, Date.now()],
    );
    if (voters.length) {
      await client.query(
        `INSERT INTO merge_voters (request_id, user_id)
         SELECT $1, voter FROM unnest($2::int[]) AS voter ON CONFLICT DO NOTHING`,
        [rows[0].id, voters],
      );
    }
    await client.query('COMMIT');
    return rows[0].id;
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
  }
}

export async function getMergeRequest(id) {
  const row = await one(
    `SELECT r.id, r.doc_id, r.server_id, r.user_id, r.content, r.status, r.created_at, r.resolved_at,
            d.name AS doc_name, u.username AS proposer_name, u.color AS proposer_color
     FROM merge_requests r
     JOIN docs d ON d.id = r.doc_id
     JOIN users u ON u.id = r.user_id
     WHERE r.id = $1`,
    [id],
  );
  if (!row) return null;
  const [voters, votes] = await Promise.all([
    all('SELECT user_id FROM merge_voters WHERE request_id = $1', [row.id]),
    all(
      `SELECT mv.user_id, mv.vote, u.username FROM merge_votes mv
       JOIN users u ON u.id = mv.user_id WHERE mv.request_id = $1`,
      [row.id],
    ),
  ]);
  return {
    id: row.id,
    docId: row.doc_id,
    serverId: row.server_id,
    content: row.content,
    status: row.status,
    createdAt: row.created_at,
    resolvedAt: row.resolved_at,
    docName: row.doc_name,
    proposer: { id: row.user_id, username: row.proposer_name, color: row.proposer_color },
    voters: voters.map((v) => v.user_id),
    votes: votes.map((v) => ({ userId: v.user_id, vote: v.vote, username: v.username })),
  };
}

export async function listMergeRequests(serverId, status = 'pending') {
  const ids =
    status === 'all'
      ? await all('SELECT id FROM merge_requests WHERE server_id = $1 ORDER BY id DESC LIMIT 100', [serverId])
      : await all('SELECT id FROM merge_requests WHERE server_id = $1 AND status = $2 ORDER BY id DESC', [
          serverId, status,
        ]);
  const requests = await Promise.all(ids.map((r) => getMergeRequest(r.id)));
  return requests.filter(Boolean);
}

export function recordMergeVote(requestId, userId, vote) {
  return pool.query(
    `INSERT INTO merge_votes (request_id, user_id, vote, created_at) VALUES ($1, $2, $3, $4)
     ON CONFLICT (request_id, user_id) DO UPDATE SET vote = EXCLUDED.vote, created_at = EXCLUDED.created_at`,
    [requestId, userId, vote, Date.now()],
  );
}

export async function isMergeVoter(requestId, userId) {
  return Boolean(
    await one('SELECT 1 FROM merge_voters WHERE request_id = $1 AND user_id = $2', [requestId, userId]),
  );
}

export function resolveMergeRequest(requestId, status) {
  return pool
    .query('UPDATE merge_requests SET status = $1, resolved_at = $2 WHERE id = $3', [
      status, Date.now(), requestId,
    ])
    .then(() => getMergeRequest(requestId));
}
