const SESSION_TTL_MS = 30 * 24 * 60 * 60 * 1000;

export async function createSession(userId) {
  const token = randomBytes(32).toString('hex');
  await pool.query('INSERT INTO sessions (token, user_id, created_at) VALUES ($1, $2, $3)', [
    token, userId, Date.now(),
  ]);
  return token;
}

export async function getUserByToken(token) {
  if (!token) return null;
  const row = await one(
    `SELECT u.*, s.created_at AS session_created FROM sessions s
     JOIN users u ON u.id = s.user_id WHERE s.token = $1`,
    [token],
  );
  if (!row) return null;
  if (Date.now() - row.session_created > SESSION_TTL_MS) {
    await deleteSession(token);
    return null;
  }
  return row;
}

export function deleteSession(token) {
  return pool.query('DELETE FROM sessions WHERE token = $1', [token]);
}

export function sweepExpiredSessions() {
  return pool.query('DELETE FROM sessions WHERE created_at < $1', [Date.now() - SESSION_TTL_MS]);
}

