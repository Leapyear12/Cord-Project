const AVATAR_COLORS = [
  '#d9655a', '#d98e4f', '#c9b14f', '#74a85c', '#4fa38d',
  '#5686d9', '#8a74d4', '#c26fac', '#d1628b', '#5e9db8',
];

function pickColor(username) {
  let total = 0;
  for (const ch of username) total += ch.codePointAt(0);
  return AVATAR_COLORS[total % AVATAR_COLORS.length];
}

export function slugifyChannel(name) {
  return String(name)
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9\-_ ]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^[-_]+|[-_]+$/g, '')
    .slice(0, 32);
}

