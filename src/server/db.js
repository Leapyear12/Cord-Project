function attachmentShape(row) {
  return {
    id: row.id,
    name: row.name,
    mime: row.mime,
    size: row.size,
  };
}

async function attachmentsByMessage(messageIds) {
  const map = new Map();
  if (!messageIds.length) return map;
  const rows = await all(
    'SELECT * FROM attachments WHERE message_id = ANY($1::int[]) ORDER BY id',
    [messageIds],
  );
  for (const row of rows) {
    const list = map.get(row.message_id) ?? [];
    list.push(attachmentShape(row));
    map.set(row.message_id, list);
  }
  return map;
}

function shapeMessage(row, attachments = []) {
  return {
    id: row.id,
    content: row.content,
    createdAt: row.created_at,
    editedAt: row.edited_at ?? null,
    threadId: row.thread_id ?? null,
    mergeId: row.merge_id ?? null,
    replyCount: row.reply_count ?? 0,
    attachments,
    user: { id: row.user_id, username: row.username, color: row.color },
  };
}

const MESSAGE_SELECT = `SELECT m.id, m.content, m.created_at, m.edited_at, m.thread_id, m.merge_id,
                               (SELECT COUNT(*) FROM messages r WHERE r.thread_id = m.id) AS reply_count,
                               u.id AS user_id, u.username, u.color
                        FROM messages m JOIN users u ON u.id = m.user_id`;

async function shapeRows(rows) {
  const attachments = await attachmentsByMessage(rows.map((r) => r.id));
  return rows.map((row) => shapeMessage(row, attachments.get(row.id) ?? []));
}

export async function listMessages(channelId, beforeId, limit = 50) {
  const rows = beforeId
    ? await all(
        `${MESSAGE_SELECT}
         WHERE m.channel_id = $1 AND m.thread_id IS NULL AND m.id < $2
         ORDER BY m.id DESC LIMIT $3`,
        [channelId, beforeId, limit],
      )
    : await all(
        `${MESSAGE_SELECT}
         WHERE m.channel_id = $1 AND m.thread_id IS NULL
         ORDER BY m.id DESC LIMIT $2`,
        [channelId, limit],
      );
  return shapeRows(rows.reverse());
}

export function listThreadReplies(channelId, rootId) {
  return all(
    `${MESSAGE_SELECT}
     WHERE m.channel_id = $1 AND m.thread_id = $2
     ORDER BY m.id ASC`,
    [channelId, rootId],
  ).then(shapeRows);
}

